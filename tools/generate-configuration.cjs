const { readFileSync, writeFileSync, mkdirSync } = require('node:fs');
const path = require('node:path');
const { createHash } = require('node:crypto');
const Ajv = require('ajv');
const standaloneCode = require('ajv/dist/standalone').default;
const { compile } = require('json-schema-to-typescript');

const root = path.resolve(__dirname, '..');
const names = ['combat', 'simulation'];
const digest = bytes => createHash('sha256').update(bytes).digest('hex');

async function generateConfiguration(check = false, projectRoot = root) {
    const ajv = new Ajv({ strict: true, allErrors: true, ownProperties: true, code: { source: true, lines: true } });
    const output = new Map();
    const hashes = {};
    for (const name of names) {
        const schema = JSON.parse(readFileSync(path.join(projectRoot, `schemas/${name}.schema.json`), 'utf8'));
        ajv.addSchema(schema, name);
        const typeName = `${name[0].toUpperCase()}${name.slice(1)}Configuration`;
        output.set(`src/contracts/generated/${name}.d.ts`, await compile({ ...schema, title: typeName }, typeName, {
            bannerComment: '/* Generated from schemas/. Run npm run generate:config; do not edit. */',
            style: { singleQuote: true, tabWidth: 4 },
        }));
        hashes[name] = digest(readFileSync(path.join(projectRoot, `public/config/${name}.json`)));
    }
    output.set('src/contracts/generated/validators.js', '/* Generated by Ajv. Run npm run generate:config; do not edit. */\n'
        + standaloneCode(ajv, { validateCombat: 'combat', validateSimulation: 'simulation' }) + '\n');
    output.set('src/contracts/generated/validators.d.ts', `/* Generated. Run npm run generate:config; do not edit. */
import type { CombatConfiguration } from './combat';
import type { SimulationConfiguration } from './simulation';
interface Validator<T> {
    (value: unknown): value is T;
    errors?: null | readonly { instancePath: string; message?: string; params: Record<string, unknown> }[];
}
export const validateCombat: Validator<CombatConfiguration>;
export const validateSimulation: Validator<SimulationConfiguration>;
`);
    const labBytes = readFileSync(path.join(projectRoot, 'public/config/lab.json'));
    require('./lab-configuration.cjs').parseLabConfiguration(JSON.parse(labBytes.toString('utf8')));
    hashes.lab = digest(labBytes);
    const healthBytes = readFileSync(path.join(projectRoot, 'public/config/route-health.json'));
    require('./route-content.cjs').parseRouteHealthPolicy(JSON.parse(healthBytes.toString('utf8')));
    hashes['route-health'] = digest(healthBytes);
    const encounterBytes = readFileSync(path.join(projectRoot, 'public/config/encounter-rules.json'));
    require('./route-content.cjs').parseEncounterRulesPolicy(JSON.parse(encounterBytes.toString('utf8')));
    hashes['encounter-rules'] = digest(encounterBytes);
    const version = digest(JSON.stringify(hashes));
    const release = { version, files: Object.fromEntries([...names, 'lab', 'route-health', 'encounter-rules'].map(name => [name, {
        path: `configuration/${version}/${name}.json`, sha256: hashes[name],
    }])) };
    output.set('src/runtime/configuration/generated/release.json', `${JSON.stringify(release, null, 2)}\n`);
    for (const [file, contents] of output) {
        const absolute = path.join(projectRoot, file);
        if (check) {
            let existing;
            try { existing = readFileSync(absolute, 'utf8'); } catch { /* Report a missing generated file as drift. */ }
            if (existing !== contents) {
                throw new Error(`${file} is stale or missing. Run npm run generate:config.`);
            }
        } else {
            mkdirSync(path.dirname(absolute), { recursive: true });
            writeFileSync(absolute, contents);
        }
    }
}

module.exports = { generateConfiguration };
if (require.main === module) {
    generateConfiguration(process.argv.includes('--check')).catch(error => {
        console.error(error.message);
        process.exitCode = 1;
    });
}
